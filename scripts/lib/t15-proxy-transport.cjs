'use strict';
// Explicit undici transport boundary. The application builds native FormData; undici 8 uses a distinct brand.
const { fetch, ProxyAgent, FormData: TransportFormData, Headers: TransportHeaders } = require('undici');
function compatibleInit(init = {}) {
    const headers = new TransportHeaders(init.headers);
    let body = init.body;
    if (body instanceof globalThis.FormData && !(body instanceof TransportFormData)) {
        const converted = new TransportFormData();
        for (const [name, value] of body.entries()) {
            if (typeof value === 'string') converted.append(name, value);
            else converted.append(name, value, value.name);
        }
        body = converted;
    }
    if (body instanceof TransportFormData && (headers.has('content-type') || headers.has('content-length'))) {
        throw Object.assign(new Error('Multipart headers must be generated by the selected transport.'), { code: 'TRANSPORT_MULTIPART_HEADERS_REJECTED' });
    }
    return { ...init, headers, body };
}
function createT15ProxyTransport(proxyUrl) {
    // Live HTTPS already tunnels. Force the same CONNECT path in the loopback HTTP wire regression.
    const dispatcher = new ProxyAgent({ uri: proxyUrl, proxyTunnel: true });
    return { fetch: (input, init = {}) => fetch(input, { ...compatibleInit(init), dispatcher }), close: () => dispatcher.close() };
}
module.exports = { createT15ProxyTransport, compatibleInit };
