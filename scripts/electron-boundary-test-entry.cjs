'use strict';
// Test-only wrapper around the real desktop main. Never ship this script or emit session credentials.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const http = require('node:http');
const path = require('node:path');
const { spawn } = require('node:child_process');
const { app, BrowserWindow, session } = require('electron');
const repo = path.resolve(__dirname, '..');
const output = process.env.NOVA_BOUNDARY_EVIDENCE;
assert.ok(output && process.env.NOVA_DATA_DIR, 'Explicit isolated test directories required');
fs.mkdirSync(output, { recursive: true });
const evidence = { startedAt: new Date().toISOString(), providerRequests: 'none', checks: {} };
let observedToken;
let primaryWindow;
let collector;
let redirectTarget;
let cspCount=0;
let seeding=false;
let seedWindow;
const captures = [];
const authorized = [];
const errors = [];
const check = (name, value) => { assert.ok(value, name); evidence.checks[name] = true; };
const until = async (fn, timeout = 20000) => { const end = Date.now() + timeout; while (Date.now() < end) { const value = await fn(); if (value) return value; await new Promise(resolve => setTimeout(resolve, 100)); } throw new Error('Timed out'); };
async function run(window) {
  primaryWindow = window;
  const contents = window.webContents;
  const origin = new URL(contents.getURL()).origin;
  evidence.backendOrigin=origin;
  check('occupied startup port resolved without collision', Number(new URL(origin).port) !== Number(process.env.NOVA_BACKEND_PORT));
  await until(() => contents.executeJavaScript('document.readyState === "complete" && !document.getElementById("app-boot-loader") && document.body.innerText.length > 30'));
  const evaluate = expression => contents.executeJavaScript(expression, true);
  check('no default remote debugging listener configured', !app.commandLine.hasSwitch('remote-debugging-port'));
  check('default Agent and browser automation disabled', await evaluate('window.novaDesktop.features.agent === false && window.novaDesktop.features.browserAutomation === false && window.novaDesktop.features.serviceWorker === false'));
  check('no Agent tab mounted', await evaluate('![...document.querySelectorAll("[role=tab]")].some(tab => tab.textContent === "Agent")'));
  check('image workbench selected', await evaluate('[...document.querySelectorAll("[role=tab]")].some(tab => tab.textContent.includes("生图工作台") && tab.getAttribute("aria-selected") === "true")'));
  check('Node globals absent', await evaluate('typeof require === "undefined" && typeof process === "undefined"'));
  check('real renderer HTTP authorized', await evaluate('fetch("/api/nova/config").then(r=>r.status===200)'));
  check('renderer cannot forge session authority', await evaluate('fetch("/api/nova/config",{headers:{"x-nova-session":"forged"}}).then(r=>r.status===200)'));
  check('real renderer WS authorized', await evaluate('new Promise(resolve=>{const ws=new WebSocket(location.origin.replace("http:","ws:")+"/api/nova/ws");const timer=setTimeout(()=>{ws.close();resolve(false)},4000);ws.onopen=()=>{clearTimeout(timer);ws.close();resolve(true)};ws.onerror=()=>{clearTimeout(timer);resolve(false)}})'));
  check('unauthenticated HTTP denied', (await fetch(origin + '/api/nova/config')).status === 403);
  check('session captured only in test main', Boolean(observedToken));
  const rendererState = await evaluate('JSON.stringify({bridge:window.novaDesktop,localStorage:{...localStorage},sessionStorage:{...sessionStorage},cookies:document.cookie})');
  check('session absent from renderer bridge/storage/cookies', !rendererState.includes(observedToken));
  check('session absent from process argv/env', !JSON.stringify({ argv:process.argv,env:process.env }).includes(observedToken));
  check('runtime info uses narrow IPC', await evaluate('window.novaDesktop.getRuntimeInfo().then(r=>r.ok && r.storageMode === "override" && !r.path && !r.directory && !r.token)'));
  check('renderer paths rejected by asset IPC', await evaluate('window.novaDesktop.revealAsset("C:\\\\secret.txt").then(r=>r.code === "INVALID_ASSET_ID")'));
  check('valid asset explicitly not ready before T03/T08', await evaluate('window.novaDesktop.saveAssetCopy("00000000-0000-4000-8000-000000000001").then(r=>r.code === "ASSET_SERVICE_NOT_READY")'));
  const reloaded = new Promise(resolve=>contents.once('did-finish-load',resolve));
  contents.reload(); await reloaded;
  await until(()=>evaluate('document.readyState === "complete" && !document.getElementById("app-boot-loader")'));
  check('desktop CSP covers original and reloaded document', cspCount >= 2);
  check('real HTTP and WS remain authorized after reload', await evaluate('Promise.all([fetch("/api/nova/config").then(r=>r.status===200),new Promise(resolve=>{const ws=new WebSocket(location.origin.replace("http:","ws:")+"/api/nova/ws");ws.onopen=()=>{ws.close();resolve(true)};ws.onerror=()=>resolve(false)})]).then(v=>v.every(Boolean))'));
  const registrations = await evaluate('navigator.serviceWorker.getRegistrations().then(r=>r.length)');
  check('desktop has no registered service worker', registrations === 0);
  check('desktop service worker registration blocked', await evaluate('navigator.serviceWorker.register("/sw.js").then(()=>false,()=>true)'));
  await evaluate('window.__boundaryCsp=[];document.addEventListener("securitypolicyviolation",e=>window.__boundaryCsp.push(e.violatedDirective))');
  const workerStatus = await evaluate('new Promise(resolve=>{let worker;try{worker=new Worker(URL.createObjectURL(new Blob(["fetch("+JSON.stringify(location.origin+"/api/nova/config")+").then(r=>postMessage(r.status)).catch(()=>postMessage(0))"],{type:"text/javascript"})))}catch(error){resolve(error.name==="SecurityError"?-2:-3);return}const timer=setTimeout(()=>{worker.terminate();resolve(-1)},4000);worker.onerror=e=>{e.preventDefault();clearTimeout(timer);worker.terminate();resolve(-2)};worker.onmessage=e=>{clearTimeout(timer);worker.terminate();resolve(e.data)}})');
  evidence.workerStatus = workerStatus;
  evidence.cspViolations = await evaluate('window.__boundaryCsp');
  check('worker cannot access backend session', workerStatus === 403 || (workerStatus === -2 && evidence.cspViolations.includes('worker-src')));
  const iframeStatus = await evaluate("(()=>new Promise(resolve=>{const frame=document.createElement('iframe');frame.src=location.origin+'/';const timer=setTimeout(()=>{frame.remove();resolve(-1)},600);frame.onload=()=>{try{frame.contentWindow.fetch(location.origin+'/api/nova/config').then(r=>{clearTimeout(timer);frame.remove();resolve(r.status)}).catch(()=>{clearTimeout(timer);frame.remove();resolve(0)})}catch{clearTimeout(timer);frame.remove();resolve(0)}};document.body.appendChild(frame)}))()");
  evidence.iframeStatus = iframeStatus;
  evidence.cspViolations = await evaluate('window.__boundaryCsp');
  check('iframe cannot access backend session', iframeStatus !== 200 && evidence.cspViolations.includes('frame-src'));
  const other = new BrowserWindow({ show: false, webPreferences: { contextIsolation:true, nodeIntegration:false, sandbox:true } });
  await other.loadURL(origin);
  const otherStatus = await other.webContents.executeJavaScript('fetch("/api/nova/config").then(r=>r.status)');
  check('other webContents cannot access backend session', otherStatus === 403);
  other.destroy();
  const web = new BrowserWindow({ show:false, webPreferences:{ partition:'t02-web-'+Date.now(),contextIsolation:true,nodeIntegration:false,sandbox:true } });
  await web.loadURL(origin);
  await until(() => web.webContents.executeJavaScript('[...document.querySelectorAll("[role=tab]")].some(tab=>tab.textContent === "Agent" && tab.getAttribute("aria-selected") === "true")'));
  check('Web default Agent retained', true);
  await until(() => web.webContents.executeJavaScript('navigator.serviceWorker.getRegistrations().then(r=>r.length > 0)'));
  check('Web PWA registration retained', true);
  web.destroy();
  collector = http.createServer((req, res) => { captures.push({ sessionHeaderPresent: Boolean(req.headers['x-nova-session']), url: req.url }); res.writeHead(200, { 'content-type':'application/json', 'access-control-allow-origin':'*', 'access-control-allow-headers':'*' }); res.end(JSON.stringify({ sessionHeaderPresent: Boolean(req.headers['x-nova-session']) })); });
  await new Promise(resolve => collector.listen(0,'127.0.0.1',resolve));
  const remote = 'http://127.0.0.1:' + collector.address().port;
  await evaluate('fetch('+JSON.stringify(remote + '/direct')+',{headers:{"x-nova-session":"renderer-forged"}}).then(r=>r.text()).catch(()=>null)');
  redirectTarget = remote+'/redirect';
  await evaluate('fetch("/api/nova/config?boundary_redirect=1").then(r=>r.text()).catch(()=>null)');
  check('remote requests and redirect never receive local session', captures.some(item=>item.url==='/direct') && captures.some(item=>item.url==='/redirect') && captures.every(item=>!item.sessionHeaderPresent));
  redirectTarget = null;
  evidence.authorizedRequestKinds = [...new Set(authorized)];
  check('observed actual WS session header', authorized.includes('webSocket'));
  const alternatePort = Number(new URL(origin).port) + 20;
  const second = spawn(process.execPath, [repo], { cwd:repo,env:{...process.env,NOVA_BACKEND_PORT:String(alternatePort)},windowsHide:true,stdio:['ignore','pipe','pipe'] });
  let secondOutput=''; second.stdout.on('data',chunk=>{secondOutput+=chunk});second.stderr.on('data',chunk=>{secondOutput+=chunk});
  const secondCode=await Promise.race([new Promise(resolve=>second.once('exit',resolve)),new Promise((_,reject)=>setTimeout(()=>{second.kill();reject(new Error('Second process did not exit'))},5000))]);
  check('same profile second instance exits before backend opens', secondCode===0 && !secondOutput.includes('server ready'));
  check('primary backend still healthy', await evaluate('fetch("/api/nova/queue-status").then(r=>r.status===200)'));
  check('no renderer exceptions or hydration errors', errors.length === 0);
  evidence.defaultCdpConfig = await evaluate('fetch("/api/nova/config").then(r=>r.json()).then(v=>JSON.stringify(v))');
  evidence.errors=errors;
}
app.on('browser-window-created', (_event, window) => {
  if (seeding || primaryWindow) return;
  primaryWindow = window;
  if(seedWindow){seedWindow.destroy();seedWindow=null;}
  window.webContents.on('console-message', (_event, details) => { if (details.level === 'error' && /hydration|Minified React|Unhandled|Uncaught/.test(details.message)) errors.push(details.message); });
  window.webContents.once('did-finish-load', () => { run(window).then(()=>{evidence.status='passed';}).catch(error=>{evidence.status='failed';evidence.error=error.stack;}).finally(async()=>{
    collector?.closeAllConnections?.(); await new Promise(resolve=>collector ? collector.close(resolve):resolve());
    evidence.finishedAt=new Date().toISOString();
    fs.writeFileSync(path.join(output,'evidence.json'),JSON.stringify(evidence,null,2)+'\n');
    console.log('T02 native boundary '+evidence.status);
    app.quit();
  }); });
});
app.whenReady().then(()=>{
  const desktopSession=session.defaultSession;
  const originalClear=desktopSession.clearStorageData.bind(desktopSession);
  desktopSession.clearStorageData=async options=>{
    check('storage cleanup scoped to app origin and worker caches', /^http:\/\/127\.0\.0\.1:\d+$/.test(options.origin) && JSON.stringify(options.storages) === JSON.stringify(['serviceworkers','cachestorage']));
    seeding=true;
    const own=http.createServer((_req,res)=>res.end('<!doctype html><title>seed</title>'));
    const external=http.createServer((_req,res)=>res.end('<!doctype html><title>external seed</title>'));
    await new Promise(resolve=>own.listen(Number(new URL(options.origin).port),'127.0.0.1',resolve));
    await new Promise(resolve=>external.listen(0,'127.0.0.1',resolve));
    seedWindow=new BrowserWindow({show:false,webPreferences:{contextIsolation:true,nodeIntegration:false,sandbox:true}});
    await seedWindow.loadURL(options.origin);
    await seedWindow.webContents.executeJavaScript('localStorage.setItem("t02-preserved","yes");caches.open("t02-own-cache").then(c=>c.put("/probe",new Response("own")))');
    await seedWindow.loadURL('http://127.0.0.1:'+external.address().port);
    await seedWindow.webContents.executeJavaScript('caches.open("t02-unrelated-cache").then(c=>c.put("/probe",new Response("other")))');
    await originalClear(options);
    check('unrelated origin CacheStorage survives startup cleanup',await seedWindow.webContents.executeJavaScript('caches.has("t02-unrelated-cache")'));
    await seedWindow.loadURL(options.origin);
    check('app origin worker cache removed',!(await seedWindow.webContents.executeJavaScript('caches.has("t02-own-cache")')));
    check('app localStorage preserved',await seedWindow.webContents.executeJavaScript('localStorage.getItem("t02-preserved")==="yes"'));
    own.closeAllConnections();external.closeAllConnections();
    await Promise.all([new Promise(resolve=>own.close(resolve)),new Promise(resolve=>external.close(resolve))]);
    seeding=false;
  };
  const webRequest=session.defaultSession.webRequest;
  const original=webRequest.onHeadersReceived.bind(webRequest);
  webRequest.onHeadersReceived=(filter,listener)=>{
    if(!listener) return original(filter,listener);
    return original(filter,(details,callback)=>listener(details,result=>{
      const headers=result.responseHeaders || details.responseHeaders || {};
      if(details.resourceType === 'mainFrame' && Object.entries(headers).some(([key,value])=>key.toLowerCase()==='content-security-policy' && value.some(item=>item.includes("worker-src 'none'")))) cspCount++;
      if(redirectTarget && details.url.includes('boundary_redirect=1')) callback({...result,responseHeaders:{...headers,Location:[redirectTarget]},statusLine:'HTTP/1.1 302 Found'});
      else callback(result);
    }));
  };

  session.defaultSession.webRequest.onSendHeaders({urls:['<all_urls>']}, details=>{
    const value=Object.entries(details.requestHeaders).find(([key])=>key.toLowerCase()==='x-nova-session')?.[1];
    if(value){observedToken=value;authorized.push(details.resourceType);}
  });
});
