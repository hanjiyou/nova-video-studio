'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const { spawn } = require('node:child_process');
const Database = require('better-sqlite3');
const repo=path.resolve(__dirname,'..');
const output=path.resolve(process.argv[2] || path.join(repo,'temp/t02-native-'+Date.now()));
fs.mkdirSync(output,{recursive:true});
const data=path.join(output,'data');
assert.ok(!fs.existsSync(data),'Fresh isolated data directory required');
const occupied=http.createServer((_req,res)=>res.end('occupied'));
let child;
let exited;
(async()=>{
  await new Promise(resolve=>occupied.listen(0,'127.0.0.1',resolve));
  const env={...process.env,NOVA_BOUNDARY_EVIDENCE:output,NOVA_DATA_DIR:data,NOVA_BACKEND_PORT:String(occupied.address().port),NODE_ENV:'production'};
  for(const key of ['ELECTRON_RUN_AS_NODE','PORTABLE_EXECUTABLE_DIR','NOVA_AGENT_ENABLED','NOVA_CDP_ENABLED','NOVA_CDP_LAUNCH_ENABLED','NOVA_ELECTRON_CDP_ENABLED']) delete env[key];
  child=spawn(require('electron'),[path.join(repo,'scripts/electron-boundary-test-entry.cjs')],{cwd:repo,env,windowsHide:true,stdio:['ignore','pipe','pipe']});
  child.stdout.on('data',chunk=>fs.appendFileSync(path.join(output,'stdout.log'),chunk));
  child.stderr.on('data',chunk=>fs.appendFileSync(path.join(output,'stderr.log'),chunk));
  child.once('exit',(code,signal)=>{exited={code,signal}});
  const timeout=setTimeout(()=>child.kill(),60000);
  await new Promise((resolve,reject)=>{child.once('exit',resolve);child.once('error',reject)});
  clearTimeout(timeout);
  assert.equal(exited.code,0,'Electron process clean exit');
  const evidence=JSON.parse(fs.readFileSync(path.join(output,'evidence.json'),'utf8'));
  assert.equal(evidence.status,'passed',evidence.error);
  const db=new Database(path.join(data,'nova-tasks.sqlite'),{readonly:true,fileMustExist:true});
  evidence.databaseQuickCheck=db.pragma('quick_check');db.close();
  assert.deepEqual(evidence.databaseQuickCheck,[{quick_check:'ok'}]);
  assert.ok(!fs.existsSync(path.join(data,'nova-tasks.sqlite-wal')) || fs.statSync(path.join(data,'nova-tasks.sqlite-wal')).size===0,'WAL checkpointed');
  evidence.cleanExit=exited;evidence.occupiedPort=occupied.address().port;
  fs.writeFileSync(path.join(output,'evidence.json'),JSON.stringify(evidence,null,2)+'\n');
  console.log(JSON.stringify(evidence,null,2));
})().catch(error=>{console.error(error);process.exitCode=1}).finally(()=>{occupied.closeAllConnections?.();occupied.close();if(child && !exited)child.kill()});
